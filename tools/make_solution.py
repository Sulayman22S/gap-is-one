"""Writes Solution.lean from the files of Conj2/.

Solution.lean is the whole proof development in one Lean module that imports only Mathlib, so
that it can be judged against Challenge.lean on its own (`lake comparator`). It is generated:
edit the files of Conj2/ and run

    python tools/make_solution.py

Each file of Conj2/ becomes one section, in dependency order, with its `import` lines removed.
A section keeps the `open` commands of a file from leaking into the next one.
"""
import io
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
ORDER = ["Rayleigh", "Graph", "Main", "PathLemmas", "Family", "SharpLemmas", "Transfer", "Sharp",
         "BestConstant"]

HEADER = """module

public import Mathlib

@[expose] public section

/-!
# The best constant in `λ₂ ≤ μ₁ − c` is `1`: the proofs

For a connected simple graph `G` on `n ≥ 2` vertices, `λ₂(G)` is the second largest eigenvalue of
the adjacency matrix and `μ₁(G)` the largest eigenvalue of the Laplacian matrix. This module proves
the three theorems that `Challenge.lean` states:

* `Conj2.best_constant`: `λ₂(G) ≤ μ₁(G) − c` holds for every such graph if and only if `c ≤ 1`;
* `Conj2.conjecture_two_false`: Conjecture 2 of T. Cazenave, arXiv:2611.03879, is false;
* `Conj2.Family.counterexample_of_card`: there is a counterexample on `n` vertices for every
  `n ≥ 11`.

The definitions `Conj2.lambda₂` and `Conj2.mu₁` below are those of `Challenge.lean`, character
for character.

This file is generated by `tools/make_solution.py` from the nine files of `Conj2/`, in
dependency order, one section per file. It imports only Mathlib, so that it can be checked on
its own. Read the proofs in `Conj2/`, where each file has its own introduction.
-/

-- The option that the project's `lakefile.toml` sets for `Conj2/`, repeated here so that this
-- file does not depend on the configuration of the package it is built in.
set_option maxSynthPendingDepth 3
"""


def body(name: str) -> str:
    text = (ROOT / "Conj2" / f"{name}.lean").read_text(encoding="utf-8")
    lines = text.split("\n")
    kept = [line for line in lines if not line.startswith("import ")]
    if len(lines) - len(kept) == 0:
        raise SystemExit(f"Conj2/{name}.lean: no import line found")
    return "\n".join(kept).strip("\n")


def main() -> None:
    parts = [HEADER]
    for name in ORDER:
        parts.append(f"\nsection File{name}\n\n{body(name)}\n\nend File{name}\n")
    text = "".join(parts)
    with io.open(ROOT / "Solution.lean", "w", encoding="utf-8", newline="\n") as out:
        out.write(text)
    print(f"Solution.lean: {text.count(chr(10))} lines from {len(ORDER)} files")


if __name__ == "__main__":
    main()
